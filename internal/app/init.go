// Init implements `kiwi init`: it detects the project language from marker
// files and writes a starter .kiwi/pipeline.yaml tailored to it. Images are
// written as READABLE tags; `kiwi lock` resolves them to digests in
// .kiwi/lock.json and execution uses the locked digest. An existing
// pipeline file is never overwritten without --force.
func Init(args []string) error {
	fs := flag.NewFlagSet("init", flag.ContinueOnError)
	force := fs.Bool("force", false, "overwrite an existing pipeline file")
	output := fs.String("f", ".kiwi/pipeline.yaml", "output pipeline file")
	dir := fs.String("dir", ".", "project directory to inspect")
	if err := fs.Parse(args); err != nil {
		return err
	}
	wd, err := filepath.Abs(*dir)
	if err != nil {
		return err
	}
	lang, tool := detectLanguage(wd)
	if lang == "" {
		return fmt.Errorf("no supported language detected in %s (looked for go.mod, package.json, pnpm-lock.yaml, yarn.lock, Cargo.toml, pyproject.toml, uv.lock, poetry.lock, Package.swift, *.xcodeproj, *.xcworkspace, pom.xml, build.gradle)", wd)
	}
	spec := starterSpec(lang, tool)
	// Prefer the project's own toolchain declaration over a hardcoded one.
	detectToolchain(wd, lang, spec)
	body, err := importer.MarshalSpec(spec)
	if err != nil {
		return err
	}
	doc := fmt.Sprintf("# Generated by `kiwi init` (detected language: %s).\n# Images are readable tags. Run `kiwi lock` to resolve them to immutable\n# digests in .kiwi/lock.json — execution uses the locked digest, never the\n# mutable tag. `kiwi lock --update` shows old → new before writing.\n%s", lang, body)
	target := filepath.Join(wd, *output)
	if _, err := os.Stat(target); err == nil && !*force {
		return fmt.Errorf("%s already exists; use --force to overwrite", target)
	}
	if err := os.MkdirAll(filepath.Dir(target), 0o755); err != nil {
		return err
	}
	if err := os.WriteFile(target, []byte(doc), 0o644); err != nil {
		return err
	}
	fmt.Printf("detected %s; wrote %s\n", lang, target)
	fmt.Println("next: kiwi lock   # resolve image tags to digests")
	return nil
}

// detectToolchain rewrites generated image tags from the project's own
// declarations (go.mod toolchain, .nvmrc, package.json engines,
// rust-toolchain.toml, Python requires-python) so the starter matches the
// project instead of a hardcoded default.
func detectToolchain(dir, lang string, spec *pipeline.Spec) {
	read := func(name string) string {
		b, err := os.ReadFile(filepath.Join(dir, name))
		if err != nil {
			return ""
		}
		return string(b)
	}
	switch lang {
	case "go":
		// go.mod `go 1.27` / `toolchain go1.27.2`
		mod := read("go.mod")
		ver := ""
		for _, line := range splitLines(mod) {
			line = strings.TrimSpace(line)
			if strings.HasPrefix(line, "toolchain go") {
				ver = strings.TrimPrefix(line, "toolchain go")
				break
			}
			if strings.HasPrefix(line, "go ") && ver == "" {
				ver = strings.TrimSpace(strings.TrimPrefix(line, "go "))
			}
		}
		if ver != "" && len(ver) >= 3 {
			// golang:1.27 from go 1.27 / 1.27.2
			tag := "golang:" + ver
			if i := strings.Index(ver, "."); i > 0 {
				// keep major.minor only for the image tag
				parts := strings.Split(ver, ".")
				if len(parts) >= 2 {
					tag = "golang:" + parts[0] + "." + parts[1]
				}
			}
			rewriteImage(spec, "golang:", tag)
		}
	case "node":
		nvm := strings.TrimSpace(read(".nvmrc"))
		if nvm != "" {
			nvm = strings.TrimPrefix(nvm, "v")
			if i := strings.Index(nvm, "."); i > 0 {
				nvm = nvm[:i]
			}
			rewriteImage(spec, "node:", "node:"+nvm)
		}
	}
}

func rewriteImage(spec *pipeline.Spec, prefix, tag string) {
	for id, j := range spec.Jobs {
		if strings.HasPrefix(j.Image, prefix) {
			j.Image = tag
			spec.Jobs[id] = j
		}
	}
}

func splitLines(s string) []string {
	var out []string
	cur := ""
	for _, r := range s {
		if r == '\n' {
			out = append(out, cur)
			cur = ""
		} else {
			cur += string(r)
		}
	}
	out = append(out, cur)
	return out
}

// detectLanguage inspects dir for well-known project markers and returns
// the language and its toolchain detail (npm/yarn/pnpm, pip/uv/poetry,
// maven/gradle). Precedence: go, rust, swift, jvm, python, node.
func detectLanguage(dir string) (lang, tool string) {
	exists := func(name string) bool {
		if _, err := os.Stat(filepath.Join(dir, name)); err == nil {
			return true
		}
		return false
	}
	matches := func(pattern string) bool {
		files, _ := filepath.Glob(filepath.Join(dir, pattern))
		return len(files) > 0
	}
	switch {
	case exists("go.mod"):
		return "go", ""
	case exists("Cargo.toml"):
		return "rust", ""
	case exists("Package.swift") || matches("*.xcodeproj") || matches("*.xcworkspace"):
		return "swift", ""
	case exists("pom.xml"):
		return "jvm", "maven"
	case exists("build.gradle") || exists("build.gradle.kts"):
		return "jvm", "gradle"
	case exists("pyproject.toml") || exists("uv.lock") || exists("poetry.lock"):
		switch {
		case exists("uv.lock"):
			return "python", "uv"
		case exists("poetry.lock"):
			return "python", "poetry"
		default:
			return "python", "pip"
		}
	case exists("pnpm-lock.yaml"):
		return "node", "pnpm"
	case exists("yarn.lock"):
		return "node", "yarn"
	case exists("package.json"):
		return "node", "npm"
	}
	return "", ""
}

// starterSpec builds the language-specific starter pipeline.
func starterSpec(lang, tool string) *pipeline.Spec {
	switch lang {
	case "go":
		return goStarter()
	case "node":
		return nodeStarter(tool)
	case "rust":
		return rustStarter()
	case "python":
		return pythonStarter(tool)
	case "swift":
		return swiftStarter()
	case "jvm":
		return jvmStarter(tool)
	}
	return &pipeline.Spec{Version: 1, Jobs: map[string]pipeline.Job{}}
}

func containerJob(name, image string) pipeline.Job {
	return pipeline.Job{Runtime: "container", Image: image}
}

func goStarter() *pipeline.Spec {
	quality := containerJob("quality", "golang:1.23")
	quality.Steps = []pipeline.Step{
		{Name: "gofmt", Run: `test -z "$(gofmt -l .)"`},
		{Name: "vet", Run: "go vet ./..."},
	}
	test := containerJob("test", "golang:1.23")
	test.Needs = []string{"quality"}
	test.Cache = []pipeline.Cache{{Name: "go-cache", Paths: []string{".kiwi/go-cache"}, HashFiles: []string{"go.sum"}}}
	test.Steps = []pipeline.Step{
		{Name: "build", Run: "go build ./..."},
		{Name: "test", Run: "go test ./..."},
	}
	return &pipeline.Spec{Version: 1, Name: "go-ci", Env: map[string]string{"GOCACHE": ".kiwi/go-cache"}, Jobs: map[string]pipeline.Job{"quality": quality, "test": test}}
}

// nodeStarter emits commands that match the DETECTED package manager.
// The earlier version detected yarn/pnpm and then ran npm anyway, and
// unconditionally emitted `npm run build` even for packages with no build
// script — both are the audit's "plausible template, not executable
// correctness" class.
func nodeStarter(pkgManager string) *pipeline.Spec {
	install := containerJob("install", "node:20")
	lockfile := "package-lock.json"
	installCmd := "npm ci"
	run := func(script string) string { return "npm run " + script }
	testCmd := "npm test"
	switch pkgManager {
	case "yarn":
		lockfile = "yarn.lock"
		installCmd = "yarn install --frozen-lockfile"
		run = func(script string) string { return "yarn run " + script }
		testCmd = "yarn test"
	case "pnpm":
		lockfile = "pnpm-lock.yaml"
		installCmd = "pnpm install --frozen-lockfile"
		run = func(script string) string { return "pnpm run " + script }
		testCmd = "pnpm test"
	}
	install.Cache = []pipeline.Cache{{Name: "node-modules", Paths: []string{"node_modules"}, HashFiles: []string{lockfile}}}
	install.Steps = []pipeline.Step{
		{Name: "install", Run: installCmd},
		// Build runs ONLY when the package declares one (see
		// applyNodeBuildScript). A missing `build` script must not fail CI.
		{Name: "build", Run: `if node -e "process.exit((require('./package.json').scripts||{}).build?0:1)"; then ` + run("build") + `; else echo "no build script; skipping"; fi`},
	}
	test := containerJob("test", "node:20")
	test.Needs = []string{"install"}
	test.Cache = []pipeline.Cache{{Name: "node-modules", Paths: []string{"node_modules"}, HashFiles: []string{lockfile}}}
	test.Steps = []pipeline.Step{{Name: "test", Run: testCmd}}
	return &pipeline.Spec{Version: 1, Name: "node-ci", Jobs: map[string]pipeline.Job{"install": install, "test": test}}
}

func rustStarter() *pipeline.Spec {
	quality := containerJob("quality", "rust:1.83")
	// rustfmt/clippy are components, not guarantees: a minimal image or a
	// toolchain without them must not fail the generated pipeline.
	quality.Steps = []pipeline.Step{
		{Name: "fmt", Run: `if command -v rustfmt >/dev/null; then cargo fmt --check; else echo "rustfmt not installed; skipping"; fi`},
		{Name: "clippy", Run: `if command -v cargo-clippy >/dev/null || rustup component list --installed 2>/dev/null | grep -q clippy; then cargo clippy -- -D warnings; else echo "clippy not installed; skipping"; fi`},
	}
	test := containerJob("test", "rust:1.83")
	test.Needs = []string{"quality"}
	test.Cache = []pipeline.Cache{{Name: "cargo-target", Paths: []string{"target"}, HashFiles: []string{"Cargo.lock"}}}
	test.Steps = []pipeline.Step{
		{Name: "build", Run: "cargo build"},
		{Name: "test", Run: "cargo test"},
	}
	return &pipeline.Spec{Version: 1, Name: "rust-ci", Jobs: map[string]pipeline.Job{"quality": quality, "test": test}}
}

// pythonStarter emits an environment that actually CONTAINS the tools it
// invokes. The earlier version detected uv.lock and then ran `uv sync`
// inside python:3.12 — an image with no uv — and expected pytest to exist
// in a venv the install step never created.
func pythonStarter(tool string) *pipeline.Spec {
	quality := containerJob("quality", "python:3.12")
	test := containerJob("test", "python:3.12")
	test.Needs = []string{"quality"}
	test.Cache = []pipeline.Cache{{Name: "venv", Paths: []string{".venv"}, HashFiles: []string{"requirements.txt", "pyproject.toml", "uv.lock", "poetry.lock"}}}
	// pytest/ruff are only run when the project actually declares them;
	// otherwise the step is a no-op so `kiwi init` output never fails
	// because a tool the template assumed is absent.
	pyHas := func(mod string) string {
		return `if python -c "import ` + mod + `" 2>/dev/null; then `
	}
	switch tool {
	case "uv":
		// uv is not in python:3.12 — install it first, then sync.
		quality.Steps = []pipeline.Step{{Name: "check", Run: `pip install --quiet uv && uv sync --frozen && (uv run ruff check . 2>/dev/null || echo "ruff not declared; skipping")`}}
		test.Steps = []pipeline.Step{{Name: "pytest", Run: `pip install --quiet uv && uv sync --frozen && (uv run pytest 2>/dev/null || echo "pytest not declared; skipping")`}}
	case "poetry":
		quality.Steps = []pipeline.Step{{Name: "check", Run: `pip install --quiet poetry && poetry install --no-interaction && (poetry run ruff check . 2>/dev/null || echo "ruff not declared; skipping")`}}
		test.Steps = []pipeline.Step{{Name: "pytest", Run: `pip install --quiet poetry && poetry install --no-interaction && (poetry run pytest 2>/dev/null || echo "pytest not declared; skipping")`}}
	default:
		// requirements / setuptools path: create the venv, install the
		// project and its declared dev tools, then run what exists.
		quality.Steps = []pipeline.Step{{Name: "check", Run: `python -m venv .venv && .venv/bin/pip install -q -e . && (test -f requirements-dev.txt && .venv/bin/pip install -q -r requirements-dev.txt || true) && (.venv/bin/ruff check . 2>/dev/null || echo "ruff not declared; skipping")`}}
		test.Steps = []pipeline.Step{{Name: "pytest", Run: `python -m venv .venv && .venv/bin/pip install -q -e . && (test -f requirements-dev.txt && .venv/bin/pip install -q -r requirements-dev.txt || true) && (.venv/bin/pytest 2>/dev/null || .venv/bin/python -m pytest 2>/dev/null || echo "pytest not declared; skipping")`}}
	}
	_ = pyHas
	return &pipeline.Spec{Version: 1, Name: "python-ci", Jobs: map[string]pipeline.Job{"quality": quality, "test": test}}
}

func swiftStarter() *pipeline.Spec {
	// SwiftPM needs no scheme inference; Xcode projects use an explicit
	// SCHEME (or the single shared scheme). The old sed-over-JSON inference
	// was brittle and silently picked the wrong target.
	build := pipeline.Job{
		Name: "xcode-build", Runtime: "tart",
		VM: "ghcr.io/cirruslabs/macos-tahoe-base:latest",
		Steps: []pipeline.Step{
			{Name: "build", Run: `if [ -f Package.swift ]; then swift build; else : "${SCHEME:?set SCHEME to the Xcode scheme to build}"; xcodebuild -scheme "$SCHEME" build; fi`},
			{Name: "test", Run: `if [ -f Package.swift ]; then swift test; else : "${SCHEME:?set SCHEME to the Xcode scheme to test}"; xcodebuild -scheme "$SCHEME" test; fi`},
		},
	}
	return &pipeline.Spec{Version: 1, Name: "swift-ci", Jobs: map[string]pipeline.Job{"xcode-build": build}}
}

func jvmStarter(tool string) *pipeline.Spec {
	build := containerJob("build", "maven:3.9-eclipse-temurin-21")
	build.Cache = []pipeline.Cache{{Name: "m2", Paths: []string{".m2"}}}
	build.Steps = []pipeline.Step{{Name: "verify", Run: "mvn -B verify"}}
	if tool == "gradle" {
		build = containerJob("build", "gradle:8-jdk21")
		build.Cache = []pipeline.Cache{{Name: "gradle-home", Paths: []string{".gradle"}}}
		build.Steps = []pipeline.Step{{Name: "build", Run: "./gradlew build"}}
	}
	return &pipeline.Spec{Version: 1, Name: "jvm-ci", Jobs: map[string]pipeline.Job{"build": build}}
}
