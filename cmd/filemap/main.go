// Command filemap generates FILE_MAP.md, a deterministic inventory of the
// repository: one table row per file with the file path and a short
// description derived from the file's first doc comment line (Go, SQL) or
// first heading/comment (Markdown, YAML, TOML, JSON), with small fallbacks
// for known file kinds. Output is sorted byte-wise by path, excluding the
// .git, dist, and tmp directories.
package main

import (
	"flag"
	"fmt"
	"io"
	"io/fs"
	"os"
	"os/exec"
	"path/filepath"
	"sort"
	"strings"
)

const (
	maxDescription = 120
	outputName     = "FILE_MAP.md"
)

func main() {
	os.Exit(run(os.Args[1:], os.Stdout, os.Stderr))
}

// run executes one filemap invocation, writing normal output to stdout and
// diagnostics to stderr, and returns the process exit code. Flag parsing uses
// the package-level flag.CommandLine so that, as before, an invalid flag
// exits with status 2 (ExitOnError) in production.
func run(args []string, stdout, stderr io.Writer) int {
	// A fresh FlagSet per invocation: tests call run() more than once, and
	// re-registering on flag.CommandLine panics.
	flags := flag.NewFlagSet("filemap", flag.ContinueOnError)
	flags.SetOutput(stderr)
	root := flags.String("root", ".", "repository root to walk")
	out := flags.String("out", "", "output path (default: <root>/FILE_MAP.md)")
	check := flags.Bool("check", false, "fail if FILE_MAP.md is stale instead of writing")
	if err := flags.Parse(args); err != nil {
		return 2
	}

	abs, err := filepath.Abs(*root)
	if err != nil {
		fmt.Fprintln(stderr, "filemap:", err)
		return 1
	}
	dest := *out
	if dest == "" {
		dest = filepath.Join(abs, outputName)
	}

	paths, err := inventory(abs)
	if err != nil {
		fmt.Fprintln(stderr, "filemap:", err)
		return 1
	}

	var b strings.Builder
	fmt.Fprintf(&b, "# Kiwi CI file map\n\n")
	fmt.Fprintf(&b, "This file map is generated by `go run ./cmd/filemap`. It lists **%d files**.\n\n", len(paths))
	b.WriteString("| File | What it contains |\n")
	b.WriteString("|---|---|\n")
	for _, p := range paths {
		fmt.Fprintf(&b, "| `%s` | %s |\n", p, describe(p, filepath.Join(abs, filepath.FromSlash(p))))
	}
	generated := b.String()
	if *check {
		existing, rerr := os.ReadFile(dest)
		if rerr == nil && string(existing) == generated {
			fmt.Fprintf(stdout, "filemap: %s is up to date (%d files)\n", dest, len(paths))
			return 0
		}
		fmt.Fprintf(stderr, "filemap: %s is stale; run `go run ./cmd/filemap` to regenerate\n", dest)
		// Show the delta so a failing CI job is actionable without a
		// developer reproducing the walk locally.
		fmt.Fprintf(stderr, "filemap: --- stale vs generated diff ---\n")
		writeInventoryDiff(stderr, string(existing), generated)
		return 1
	}
	if err := os.WriteFile(dest, []byte(generated), 0o644); err != nil {
		fmt.Fprintln(stderr, "filemap:", err)
		return 1
	}
	fmt.Fprintf(stdout, "filemap: wrote %s (%d files)\n", dest, len(paths))
	return 0
}

// inventory returns the sorted repository file list that FILE_MAP.md
// describes. When the root is a git checkout the list is EXACTLY the
// git-tracked text files: that is the only set that is identical on every
// machine, so `--check` can never go stale because a developer laptop has
// extra untracked files (.mimocode/, scratch dirs, OS junk). Without git it
// falls back to a filesystem walk with the same filters.
func inventory(abs string) ([]string, error) {
	if paths, ok := gitTrackedPaths(abs); ok {
		return paths, nil
	}
	return walkPaths(abs)
}

// gitTrackedPaths lists git-tracked files under abs, filtered to the same
// text/known-kind set the walker keeps. Returns ok=false when this is not a
// git checkout or git is unavailable.
func gitTrackedPaths(abs string) ([]string, bool) {
	cmd := exec.Command("git", "-C", abs, "ls-files", "-z")
	out, err := cmd.Output()
	if err != nil {
		return nil, false
	}
	var paths []string
	for _, rel := range strings.Split(string(out), "\x00") {
		if rel == "" || rel == outputName {
			continue
		}
		if skipRel(rel) {
			continue
		}
		full := filepath.Join(abs, filepath.FromSlash(rel))
		fi, err := os.Stat(full)
		if err != nil || !fi.Mode().IsRegular() {
			continue
		}
		b, err := os.ReadFile(full)
		if err != nil || !isText(b) {
			continue
		}
		paths = append(paths, filepath.ToSlash(rel))
	}
	sort.Strings(paths)
	return paths, true
}

// walkPaths is the non-git fallback: a filesystem walk with the historical
// directory/file filters. Root-level build output is skipped by exact
// top-level name so a nested package directory named dist/ or bin/ is never
// silently dropped from the inventory (internal/dogfood/dist is source).
func walkPaths(abs string) ([]string, error) {
	var paths []string
	err := filepath.WalkDir(abs, func(p string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		rel, rerr := filepath.Rel(abs, p)
		if rerr != nil {
			return rerr
		}
		rel = filepath.ToSlash(rel)
		if rel == "." {
			return nil
		}
		if d.IsDir() {
			name := d.Name()
			// Root-scoped build/output dirs only.
			if (rel == "dist" || rel == "tmp" || rel == "bin") ||
				name == ".git" || name == "vendor" || name == "testdata" ||
				name == ".kilo" || name == ".cache" || name == "node_modules" ||
				name == ".venv" || name == ".mimocode" {
				return filepath.SkipDir
			}
			// A nested .git (Agent Manager worktree or vendored checkout)
			// means a second repository lives inside this tree; never index it.
			if _, err := os.Stat(filepath.Join(p, ".git")); err == nil {
				return filepath.SkipDir
			}
			return nil
		}
		if rel == outputName {
			return nil
		}
		if skipRel(rel) {
			return nil
		}
		if skipFile(abs, rel, d) {
			return nil
		}
		paths = append(paths, rel)
		return nil
	})
	if err != nil {
		return nil, err
	}
	sort.Strings(paths)
	return paths, nil
}

// skipRel applies the path-level exclusions shared by both inventory modes.
func skipRel(rel string) bool {
	if rel == outputName || rel == ".git" {
		return true
	}
	// testdata corpora and OS junk are never inventory content.
	for _, part := range strings.Split(rel, "/") {
		if part == "testdata" {
			return true
		}
	}
	base := rel
	if i := strings.LastIndex(rel, "/"); i >= 0 {
		base = rel[i+1:]
	}
	if base == ".DS_Store" || base == "Thumbs.db" || base == "desktop.ini" {
		return true
	}
	if strings.HasSuffix(base, ".tmp") || strings.HasSuffix(base, ".prof") || strings.HasSuffix(base, ".out") {
		return true
	}
	return false
}

// skipFile filters out generated metadata and non-source artifacts that must
// not appear in the inventory. The binary probe resolves rel beneath the walk
// root, never against the process working directory.
func skipFile(root, rel string, d fs.DirEntry) bool {
	name := d.Name()
	if name == ".git" {
		// A git WORKTREE (and kiwi's preferred local snapshot strategy)
		// carries ".git" as a regular pointer FILE; indexing it would make
		// the map differ between a checkout and a worktree and fail
		// --check everywhere a worktree is used. It is never content.
		return true
	}
	if name == ".DS_Store" || name == "Thumbs.db" || name == "desktop.ini" {
		return true
	}
	if strings.HasSuffix(name, ".tmp") || strings.HasSuffix(name, ".prof") || strings.HasSuffix(name, ".out") {
		return true
	}
	if rel == "go.sum" {
		return false
	}
	if info, err := d.Info(); err == nil && info.Mode().IsRegular() {
		if b, rerr := os.ReadFile(filepath.Join(root, filepath.FromSlash(rel))); rerr == nil && !isText(b) {
			return true
		}
	}
	return false
}

// isText reports whether the buffer looks like human-readable text (UTF-8
// with printable content) rather than a binary artifact.
func isText(b []byte) bool {
	if len(b) == 0 {
		return true
	}
	n := len(b)
	if n > 512 {
		n = 512
	}
	for _, c := range b[:n] {
		if c == 0 {
			return false
		}
	}
	return true
}

// describe returns a short, single-line description for the file at path
// abs, derived from its first doc comment line or heading.
func describe(rel, abs string) string {
	if rel == "FILE_MAP.md" {
		return "Generated inventory of every file in the repository (this file)."
	}
	data, err := os.ReadFile(abs)
	if err != nil {
		return "File could not be read."
	}
	content := string(data)
	desc := ""
	switch {
	case strings.HasSuffix(rel, ".go"):
		desc = firstGoDocComment(content)
	case strings.HasSuffix(rel, ".md"):
		desc = firstHeadingOrLine(content)
	case strings.HasSuffix(rel, ".sql"):
		desc = firstCommentOrLine(content, "--")
	case strings.HasSuffix(rel, ".yaml") || strings.HasSuffix(rel, ".yml") || strings.HasSuffix(rel, ".toml"):
		desc = firstCommentOrLine(content, "#")
	case strings.HasSuffix(rel, ".json"):
		desc = firstNonEmpty(content)
	case rel == "LICENSE":
		desc = firstNonEmpty(content)
	case rel == "Makefile":
		desc = firstCommentOrLine(content, "#")
	case rel == ".gitignore":
		desc = firstUncommentedLine(content, "#")
	default:
		desc = firstNonEmpty(content)
	}
	if desc == "" {
		desc = fallbackDescription(rel)
	}
	desc = strings.Join(strings.Fields(desc), " ")
	desc = strings.ReplaceAll(desc, "|", `\|`)
	if len(desc) > maxDescription {
		desc = desc[:maxDescription-3] + "..."
	}
	return desc
}

// firstGoDocComment returns the first line of the leading doc comment block
// above the package clause.
func firstGoDocComment(s string) string {
	lines := strings.Split(s, "\n")
	var comment []string
	for _, l := range lines {
		t := strings.TrimSpace(l)
		if t == "" {
			continue
		}
		if strings.HasPrefix(t, "//") {
			comment = append(comment, strings.TrimSpace(strings.TrimPrefix(t, "//")))
			continue
		}
		if strings.HasPrefix(t, "/*") {
			comment = append(comment, strings.TrimSpace(strings.TrimPrefix(t, "/*")))
			continue
		}
		// A non-comment line (including the package clause) ends the doc block.
		break
	}
	if len(comment) == 0 {
		return ""
	}
	return comment[0]
}

// firstHeadingOrLine returns the first Markdown heading, or the first
// non-empty line when there is none.
func firstHeadingOrLine(s string) string {
	for _, l := range strings.Split(s, "\n") {
		t := strings.TrimSpace(l)
		if t == "" {
			continue
		}
		if strings.HasPrefix(t, "#") {
			return strings.TrimSpace(strings.TrimLeft(t, "#"))
		}
		return t
	}
	return ""
}

// firstCommentOrLine returns the first comment line (stripped of the given
// comment marker), or the first non-empty line when there is none.
func firstCommentOrLine(s, marker string) string {
	var first string
	for _, l := range strings.Split(s, "\n") {
		t := strings.TrimSpace(l)
		if t == "" {
			continue
		}
		if first == "" {
			first = t
		}
		if strings.HasPrefix(t, marker) {
			return strings.TrimSpace(strings.TrimPrefix(t, marker))
		}
	}
	return first
}

// firstUncommentedLine returns the first non-empty line that does not start
// with the given marker.
func firstUncommentedLine(s, marker string) string {
	for _, l := range strings.Split(s, "\n") {
		t := strings.TrimSpace(l)
		if t == "" || strings.HasPrefix(t, marker) {
			continue
		}
		return t
	}
	return ""
}

// firstNonEmpty returns the first non-empty, trimmed line.
func firstNonEmpty(s string) string {
	for _, l := range strings.Split(s, "\n") {
		if t := strings.TrimSpace(l); t != "" {
			return t
		}
	}
	return ""
}

// fallbackDescription provides a directory-based description when a file has
// no usable header line.
func fallbackDescription(rel string) string {
	dir := filepath.Dir(rel)
	isCmd := dir == "cmd" || strings.HasPrefix(dir, "cmd"+string(filepath.Separator))
	switch {
	case strings.HasSuffix(rel, "_test.go"):
		switch {
		case dir == ".":
			return "Regression tests for the repository root."
		case isCmd:
			return "Regression tests for the " + filepath.Base(dir) + " command."
		default:
			return "Regression tests for the " + filepath.Base(dir) + " package."
		}
	case strings.HasSuffix(rel, ".go"):
		switch {
		case dir == ".":
			return "Go source in the repository root."
		case isCmd:
			return "Go source for the " + filepath.Base(dir) + " command."
		default:
			return "Go source in internal/" + filepath.Base(dir) + "."
		}
	case strings.HasSuffix(rel, ".md"):
		return "Documentation file."
	case strings.HasSuffix(rel, ".yaml") || strings.HasSuffix(rel, ".yml"):
		return "YAML configuration file."
	case strings.HasSuffix(rel, ".json"):
		return "JSON data file."
	default:
		return "Repository file."
	}
}

// writeInventoryDiff prints the set difference between the committed and
// generated inventories so a stale check names the offending paths.
func writeInventoryDiff(w io.Writer, existing, generated string) {
	oldSet := inventoryRows(existing)
	newSet := inventoryRows(generated)
	for _, p := range sortedKeys(newSet) {
		if _, ok := oldSet[p]; !ok {
			fmt.Fprintf(w, "filemap: + %s\n", p)
		}
	}
	for _, p := range sortedKeys(oldSet) {
		if _, ok := newSet[p]; !ok {
			fmt.Fprintf(w, "filemap: - %s\n", p)
		}
	}
	for _, p := range sortedKeys(newSet) {
		if o, ok := oldSet[p]; ok && o != newSet[p] {
			fmt.Fprintf(w, "filemap: ~ %s\n", p)
		}
	}
}

func inventoryRows(md string) map[string]string {
	out := map[string]string{}
	for _, line := range strings.Split(md, "\n") {
		if !strings.HasPrefix(line, "| `") {
			continue
		}
		// | `path` | desc |
		rest := line[3:]
		i := strings.Index(rest, "`")
		if i < 0 {
			continue
		}
		path := rest[:i]
		out[path] = line
	}
	return out
}

func sortedKeys(m map[string]string) []string {
	out := make([]string, 0, len(m))
	for k := range m {
		out = append(out, k)
	}
	sort.Strings(out)
	return out
}
